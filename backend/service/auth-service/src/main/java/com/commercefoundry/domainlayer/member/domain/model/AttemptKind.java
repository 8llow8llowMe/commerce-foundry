package com.commercefoundry.domainlayer.member.domain.model;

/**
 * 시도 제한을 따로 세는 종류 (#66). 같은 이메일이라도 종류마다 창을 따로 쓴다 — 한쪽 시도가 다른 쪽 한도를 깎지 않는다.
 * 저장소의 키 이름은 구현이 이 값에서 정한다.
 */
public enum AttemptKind {

    /** 로그인 — 같은 이메일로 비밀번호를 반복해 맞혀 보는 시도를 센다. */
    LOGIN,

    /**
     * 관리자 로그인(#6) — 고객 로그인과 창을 나눈다. 한 창이면 고객 로그인에 관리자 이메일을 거듭 보내는 것만으로 관리자 로그인을 잠글 수 있다.
     * 허용 횟수 · 창은 고객 로그인과 같은 값을 쓴다.
     */
    ADMIN_LOGIN,

    /** 회원가입 — 같은 이메일로 반복하는 가입 요청(중복 확인 폴링 · BCrypt 반복)을 센다. */
    SIGN_UP,

    /** 회원가입 IP 차원. 값은 게이트웨이의 불투명 HMAC 식별자다. */
    SIGN_UP_IP,

    /**
     * 관리자 OTP 코드 시도(#238) — 등록 확인 · 해제 · 복구 코드 재발급(PR-A2). 주체는 이메일이 아니라 관리자 memberId(10진 문자열)다.
     * 6자리 코드 대입을 막는 장치라 {@code auth.login-guard.enabled=false} 여도 센다. 허용 횟수 · 창은 로그인과 같은 값이다.
     * 로그인 2단계(PR-B) 창을 이 창과 나눌지는 PR-B 착수 전에 정한다 — 같은 창이면 토큰 보유자가 틀린 재인증으로 로그인 2단계를 잠글 수 있다.
     */
    ADMIN_OTP
}
